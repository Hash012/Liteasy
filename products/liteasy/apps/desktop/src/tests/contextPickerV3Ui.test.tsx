import { render, screen, within, fireEvent, act } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, test, vi } from "vitest";
import { ContextAssetBrowser } from "../app/features/assistant/ContextAssetBrowser";
import { contextPickerFixture } from "./contextPickerFixture";
import { browserStateKey, readBrowserState, writePickerRecord } from "../app/features/context-picker/pickerState";
beforeEach(() => localStorage.clear());
test("CAT-01/02/03/04: category switches atomically within one paper and selected-only is an intersection", async () => {
  const f = contextPickerFixture(3), key = browserStateKey(f.source.scope, "library", "context", "v3");
  const state = readBrowserState(key, f.source.scope); state.route = f.imageRoute; state.history = [f.imageRoute]; writePickerRecord(key, state);
  render(<ContextAssetBrowser targetDraftId="v3" catalogPort={f.catalog} suggestions={f.assets} onClose={vi.fn()} onAddContextToken={vi.fn()} />);
  const user = userEvent.setup(), sidebar = within(screen.getByRole("navigation", { name: "上下文资产筛选" }));
  await user.click(screen.getByRole("checkbox", { name: "选择 图 000", exact: true }));
  await user.click(sidebar.getByRole("button", { name: /^笔记/ }));
  expect(screen.getAllByRole("button", { name: /^预览 / }).map(node => node.getAttribute("aria-label"))).toEqual(["预览 私有笔记"]);
  await user.click(screen.getByRole("checkbox", { name: "选择 私有笔记", exact: true }));
  await user.click(sidebar.getByRole("button", { name: /^图片/ }));
  await user.click(sidebar.getByRole("button", { name: /^图片/ }));
  expect(sidebar.getByRole("button", { name: /^图片/ })).toHaveAttribute("aria-pressed", "true");
  expect(sidebar.getByRole("button", { name: /^笔记/ })).toHaveAttribute("aria-pressed", "false");
  await user.click(screen.getByRole("checkbox", { name: "只看已选" }));
  expect(screen.getAllByRole("button", { name: /^预览 / }).map(node => node.getAttribute("aria-label"))).toEqual(["预览 图 000"]);
  expect(screen.getByText("待加入 2 项")).toBeInTheDocument();
  expect(screen.getByRole("navigation", { name: "上下文位置" })).toHaveTextContent("A论文 P");
  expect(screen.getByRole("navigation", { name: "上下文位置" })).not.toHaveTextContent("提取资产");
});
test("STABLE-05: changing drafts aborts pending preview and cannot publish it in the new draft", async () => {
  let finish!: (value: { text: string }) => void;
  let signal: AbortSignal | undefined;
  const f = contextPickerFixture(1);
  const assets = [{ ...f.assets[2], loadPreview: (value?: AbortSignal) => { signal = value; return new Promise<{ text: string }>(resolve => { finish = resolve; }); } }];
  const view = render(<ContextAssetBrowser suggestions={assets} targetDraftId="old" onClose={vi.fn()} />);
  fireEvent.click(screen.getByRole("button", { name: "预览 私有笔记" }));
  await act(async () => {});
  view.rerender(<ContextAssetBrowser suggestions={assets} targetDraftId="new" onClose={vi.fn()} />);
  expect(signal?.aborted).toBe(true);
  await act(async () => finish({ text: "旧会话内容" }));
  expect(screen.queryByText("旧会话内容")).not.toBeInTheDocument();
});
