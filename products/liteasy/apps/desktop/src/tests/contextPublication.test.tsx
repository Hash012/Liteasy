import { act, fireEvent, render, renderHook, screen, within } from "@testing-library/react";
import { afterEach, expect, test, vi } from "vitest";
import { useContextPublicationController } from "../app/controllers/useContextPublicationController";
import { ContextPublicationContext } from "../app/features/research-context/contextPublication";
import { ExternalNoteEditor } from "../app/features/note-files/ExternalNoteEditor";
import { PdfAnnotationsOverview } from "../app/features/pdf/PdfAnnotationsOverview";
import { AssistantMessageList } from "../app/features/assistant/AssistantMessageList";
import { clearStoredAccountSession, storeAccountSession } from "../app/features/account/accountSessionStorage";
const session = { endpoint: "https://api.example.invalid", issuer: "https://id.example.invalid", userId: "alice", sessionId: "token", name: "A", email: "a@example.invalid", expiresAt: "2030-01-01T00:00:00Z" };
afterEach(clearStoredAccountSession);
test("an uncertain selected-source publication retries the exact operation and preserves a corrected profile", async () => {
  storeAccountSession(session);
  const client = { list: vi.fn(async () => ({ entries: [] })), write: vi.fn().mockRejectedValueOnce({ code: "context_network_unavailable" }).mockResolvedValueOnce({ entryId: "saved", revision: 1 }) };
  const hook = renderHook(() => useContextPublicationController(session, (() => client) as never));
  act(() => hook.result.current.open({ title: "选中笔记", text: "原笔记内容", basis: "user_authored", source: { provider: "liteasy", origin: "installation:A", sourceId: "note1", availability: "local_only" } }));
  await act(async () => hook.result.current.model.save());
  await act(async () => hook.result.current.model.save());
  expect(client.write.mock.calls[0][0]).toEqual(client.write.mock.calls[1][0]);
  expect(hook.result.current.model.notice).toContain("云端已保存");
  client.list.mockResolvedValue({ entries: [{ id: "already-published", revision: 4 }] } as never);
  act(() => hook.result.current.open({ kind: "profile", title: "旧画像", text: "本机原值", basis: "user_statement", source: { provider: "liteasy", origin: "installation:A", sourceId: "profile/topics" } }));
  await act(async () => hook.result.current.model.save());
  expect(client.write).toHaveBeenCalledTimes(2);
  expect(hook.result.current.model.notice).toContain("云端修正已保留");
});
test("note, annotation and conversation actions publish only the chosen source with distinct basis", () => {
  const publish = vi.fn();
  const wrap = (children: React.ReactNode) => <ContextPublicationContext.Provider value={publish}>{children}</ContextPublicationContext.Provider>;
  const note = render(wrap(<ExternalNoteEditor model={{ session: { snapshot: { mountId: "mount", path: "chosen.md", name: "选中笔记", kind: "file", text: "所选笔记", version: "v-real" }, draft: "所选笔记", editing: false, changed: false }, drafts: [], busy: false, error: "", notice: "", open: vi.fn(), setDraft: vi.fn(), setEditing: vi.fn(), save: vi.fn(), reload: vi.fn() } as never} />));
  fireEvent.click(screen.getByRole("button", { name: "保存到个人上下文" }));
  expect(publish.mock.calls[0][0]).toMatchObject({ text: "所选笔记", basis: "user_authored", source: { sourceId: "chosen.md", revision: "v-real" } });
  note.unmount();
  const annotation = { id: "a", kind: "highlight", page: 1, excerpt: "原文摘录", note: "我选择的注释", revision: 3, rects: [], createdAt: "2026-11-26T00:00:00Z", updatedAt: "2026-11-26T00:00:00Z" };
  const pdf = render(wrap(<PdfAnnotationsOverview annotations={[annotation as never]} teamAnnotations={[]} onNavigate={vi.fn()} onClose={vi.fn()} />));
  fireEvent.click(screen.getByRole("button", { name: "保存到个人上下文" }));
  expect(publish.mock.calls[1][0].text).toBe("## 资料摘录\n原文摘录\n\n## 批注笔记\n我选择的注释");
  expect(publish.mock.calls[1][0].source).toMatchObject({ sourceId: "a", revision: "3" });
  pdf.unmount();
  render(wrap(<AssistantMessageList mode="ask" messages={[{ id: "answer", role: "assistant", content: "只保存此回答" }, { id: "other", role: "assistant", content: "未选择的其他回答" }] as never} />));
  const item = screen.getByText("只保存此回答").closest("article")!;
  fireEvent.click(within(item).getByRole("button", { name: "保存到个人上下文" }));
  expect(publish.mock.calls[2][0]).toMatchObject({ text: "只保存此回答", basis: "agent_summary", source: { sourceId: "answer" } });
});
