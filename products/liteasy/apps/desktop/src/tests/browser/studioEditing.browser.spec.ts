import { expect, test } from "@playwright/test";

async function openStudio(page: import("@playwright/test").Page) {
  await page.addInitScript(() => localStorage.setItem("liteasy.account.suppress-login-reminder.v1", "true"));
  await page.goto("/");
  await page.getByRole("button", { name: "扩展", exact: true }).click();
  await page.getByRole("button", { name: "制作扩展", exact: true }).click();
}

test("offline Studio edits canonical content, preserves invalid source and restores deletion", async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1600, height: 900 });
  const modelRequests: string[] = [];
  page.on("request", (request) => { if (/\/(responses|chat\/completions)(?:[?\/]|$)/.test(request.url())) modelRequests.push(request.url()); });
  await openStudio(page);
  await page.getByRole("button", { name: "开始离线演示", exact: true }).click();
  const studio = page.locator(".workflow-studio");
  await studio.getByRole("button", { name: "研究问题", exact: true }).click();
  const text = studio.getByRole("textbox", { name: "卡片正文", exact: true });
  const viewport = studio.locator(".react-flow__viewport");
  const initialView = await viewport.getAttribute("style");
  await text.fill("## 我修改的演示问题\n\n这是离线编辑结果。");
  await text.press("Delete");
  await expect(viewport).toHaveAttribute("style", initialView!);
  await expect(studio.locator(".studio-card-list button")).toHaveCount(4);
  await studio.getByRole("button", { name: "校验与预览", exact: true }).click();
  await expect(studio.locator(".studio-preview")).toContainText("我修改的演示问题");
  await studio.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(studio.getByText("演示已完成", { exact: true })).toBeVisible();
  await studio.getByRole("tab", { name: "源码", exact: true }).click();
  const source = studio.getByRole("textbox", { name: "扩展源文件", exact: true });
  const valid = await source.inputValue();
  await source.fill(valid + "broken");
  await studio.getByLabel("项目文件").selectOption("liteasy.extension.json");
  await studio.getByLabel("项目文件").selectOption("templates/comparison.json");
  await expect(source).toHaveValue(valid + "broken");
  await studio.getByRole("tab", { name: "组合", exact: true }).click();
  await expect(studio.locator(".studio-card-list button")).toHaveCount(4);
  await studio.getByRole("tab", { name: "源码", exact: true }).click();
  await expect(source).toHaveValue(valid + "broken");
  await source.fill(valid);
  await studio.getByRole("tab", { name: "组合", exact: true }).click();
  await studio.getByRole("button", { name: "研究问题", exact: true }).click();
  const node = studio.locator('.react-flow__node[data-id="question"]');
  const handle = await node.locator("header").boundingBox();
  await page.mouse.move(handle!.x + 20, handle!.y + 10);
  await page.mouse.down();
  await page.mouse.move(handle!.x + 50, handle!.y + 20, { steps: 5 });
  await page.mouse.up();
  await studio.getByRole("tab", { name: "源码", exact: true }).click();
  expect(JSON.parse(await source.inputValue()).cards.find((card: { id: string }) => card.id === "question").position.x).toBeGreaterThan(20);
  await studio.getByRole("tab", { name: "组合", exact: true }).click();
  await node.click({ position: { x: 10, y: 10 } });
  await node.focus();
  await node.press("Delete");
  await expect(studio.locator(".studio-card-list button")).toHaveCount(3);
  await studio.getByRole("button", { name: "撤销", exact: true }).click();
  await expect(studio.locator(".studio-card-list button")).toHaveCount(4);
  await studio.getByRole("button", { name: "重做", exact: true }).click();
  await expect(studio.locator(".studio-card-list button")).toHaveCount(3);
  await studio.getByRole("button", { name: "保存草稿", exact: true }).click();
  await page.screenshot({ path: info.outputPath("studio-after-wide.png"), fullPage: true });
  const beforeResize = await viewport.getAttribute("style");
  await studio.evaluate((el) => { (el as HTMLElement).style.width = "420px"; (el as HTMLElement).style.maxWidth = "420px"; });
  await studio.getByRole("button", { name: "属性", exact: true }).click();
  await expect(viewport).toHaveAttribute("style", beforeResize!);
  await page.screenshot({ path: info.outputPath("studio-after-420.png"), fullPage: true });
  await expect(studio.locator(".studio-properties")).toBeVisible();
  expect(modelRequests).toEqual([]);
  await page.reload();
  await page.getByRole("button", { name: "扩展", exact: true }).click();
  await page.getByRole("button", { name: "制作扩展", exact: true }).click();
  await page.locator(".studio-more > summary").click();
  await page.getByLabel("选择扩展草稿").selectOption({ label: "离线演示：四张研究卡片" });
  await expect(studio.locator(".studio-card-list button")).toHaveCount(3);
});
