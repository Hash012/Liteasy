import { expect, test } from "@playwright/test";

for (const width of [320, 400, 520]) test(`profile and organization controls preserve choices and expose failures at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/src/tests/browser/fixtures/profile-controls-review.html");
  await expect(page.locator("main select, main details")).toHaveCount(0);
  const stage = page.getByRole("combobox", { name: "研究阶段", exact: true });
  await stage.focus(); await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("option", { name: "博士研究生", exact: true })).toBeVisible();
  await page.screenshot({ animations: "disabled", path: info.outputPath(`profile-picker-${width}.png`) });
  await page.keyboard.press("Home");
  await page.keyboard.press("ArrowDown"); await page.keyboard.press("ArrowDown"); await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Enter");
  await expect(stage).toBeFocused();
  await expect(stage).toContainText("博士研究生");
  await page.getByRole("button", { name: "阅读讲解（可选）" }).click();
  await page.getByRole("combobox", { name: "自动标注的讲解深度" }).click();
  await page.getByRole("option", { name: "高阶 · 评析精妙之处" }).click();
  await page.getByRole("button", { name: "阅读讲解（可选）" }).click();
  await page.getByRole("button", { name: "保存学术档案" }).click();
  await expect(page.getByLabel("已保存画像")).toContainText('"stage":"博士研究生"');
  await expect(page.getByLabel("已保存画像")).toContainText('"readingExplanation":"advanced"');
  await page.getByRole("button", { name: "已记偏好", exact: true }).click();
  await page.getByRole("button", { name: "添加偏好" }).click();
  await page.getByRole("combobox", { name: "偏好类别" }).click();
  await page.getByRole("option", { name: "回答方式", exact: true }).click();
  await page.getByRole("textbox", { name: "偏好内容" }).fill("先展示可核对的研究证据");
  await page.getByRole("button", { name: "保存偏好" }).click();
  await page.getByRole("button", { name: "来源与更新时间：先展示可核对的研究证据" }).click();
  await expect(page.getByText("手动维护的偏好", { exact: true })).toBeVisible();
  await page.screenshot({ animations: "disabled", path: info.outputPath(`memory-evidence-${width}.png`) });
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "组织", exact: true }).click();
  await expect(page.getByText("文献库暂不可用，请刷新组织空间后重试。")).toBeVisible();
  await expect(page.getByText("暂无法获取权限说明，请刷新组织空间后重试。")).toBeVisible();
  await expect(page.getByRole("button", { name: "打开共享文献库" })).toBeDisabled();
  await page.getByRole("button", { name: /^成员/ }).click();
  await expect(page.getByText("Ada Lovelace", { exact: true })).toBeVisible();
  await page.screenshot({ animations: "disabled", path: info.outputPath(`organization-expanded-${width}.png`) });
  await page.getByRole("button", { name: "深色", exact: true }).click();
  await page.screenshot({ animations: "disabled", path: info.outputPath(`organization-error-dark-${width}.png`) });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  expect(overflow).toBe(false);
});
