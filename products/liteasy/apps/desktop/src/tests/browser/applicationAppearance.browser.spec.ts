import { expect, test } from "@playwright/test";

test("appearance follows the system and an explicit choice persists across launches", async ({ page }, testInfo) => {
  test.setTimeout(75_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem("liteasy.account.suppress-login-reminder.v1", "true"));
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.emulateMedia({ colorScheme: "dark" });
  await page.goto("/");
  // A cold Vite launch must mount the application before checking its theme.
  await expect(page.getByRole("navigation", { name: "左边栏导航" })).toBeVisible({ timeout: 30_000 });
  await expect(page.locator("html")).toHaveAttribute("data-color-scheme", "dark");
  const settings = page.getByRole("navigation", { name: "左边栏导航" }).getByRole("button", { name: "设置", exact: true });
  await settings.click();
  const appearance = page.getByRole("combobox", { name: "外观", exact: true });
  await expect(appearance).toHaveText("跟随系统");
  await expect(page.locator(".activity-bar")).toHaveCSS("background-color", "rgb(22, 27, 36)");
  await expect(page.locator(".reader-layout-button:not(.active)").first()).toHaveCSS("background-color", "rgb(37, 46, 59)");
  const assistantHome = page.getByRole("region", { name: "助手首页", exact: true });
  await expect(assistantHome.getByText("直接提问，或用 @ 添加资料、/ 选择命令。", { exact: true })).toBeVisible();
  await expect(assistantHome).toHaveCSS("color", "rgb(226, 232, 240)");
  await expect(page.locator(".assistant-input-highlight")).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
  const navigation = page.getByRole("group", { name: "对话与任务导航" });
  await expect(navigation.getByRole("button", { name: "首页", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("combobox", { name: "界面字号", exact: true }).click();
  const options = page.getByRole("listbox");
  await expect(options).toBeVisible();
  await expect(options).toHaveCSS("color", "rgb(226, 232, 240)");
  await page.keyboard.press("Escape");
  await appearance.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("appearance-dark.png"), fullPage: true, animations: "disabled" });
  await appearance.click();
  await page.getByRole("option", { name: "浅色", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-color-scheme", "light");
  await expect(page.locator(".activity-bar")).toHaveCSS("background-color", "rgb(243, 244, 246)");
  await expect(assistantHome).toHaveCSS("color", "rgb(15, 23, 42)");
  await page.screenshot({ path: testInfo.outputPath("appearance-light.png"), fullPage: true, animations: "disabled" });
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("data-color-scheme", "light");
  if (!(await appearance.isVisible())) await settings.click();
  await expect(appearance).toHaveText("浅色");
  await appearance.click();
  await page.getByRole("option", { name: "跟随系统", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-color-scheme", "dark");
  await page.emulateMedia({ colorScheme: "light" });
  await expect(page.locator("html")).toHaveAttribute("data-color-scheme", "light");
  expect(errors).toEqual([]);
});
