import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("failure diagnostics stay collapsed, export redacted text and become previewable conversation context", async ({ page }, info) => {
  await page.goto("/src/tests/browser/fixtures/assistant-root-cause.html?diagnostic=1");
  await page.getByRole("button", { name: "任务", exact: true }).click();
  await page.getByRole("button", { name: "打开会话：生成：薄读" }).click();
  await expect(page.getByRole("alert")).toContainText("结构化输出方式");
  await expect(page.getByText(/技术关联：任务/)).not.toBeVisible();
  await page.screenshot({ path: info.outputPath("failure-summary-light.png"), animations: "disabled" });
  await page.getByRole("button", { name: "查看诊断日志", exact: true }).click();
  await expect(page.getByText(/技术关联：任务/)).toBeVisible();
  const pending = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出日志", exact: true }).click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe("Liteasy-任务诊断日志.txt");
  const text = await readFile((await download.path())!, "utf8");
  expect(text).toContain("unsupported response_format");
  expect(text).not.toContain("fixture-secret");
  await page.getByRole("button", { name: "让 AI 分析错误", exact: true }).click();
  await expect(page.getByPlaceholder("输入你的问题或命令")).toHaveValue(/请根据这份诊断日志/);
  await page.getByRole("button", { name: "深色", exact: true }).click();
  await page.getByRole("button", { name: "预览上下文：任务诊断日志", exact: true }).click();
  await expect(page.getByLabel("上下文预览")).toContainText("fixture-model");
  await page.screenshot({ path: info.outputPath("diagnostic-context-dark.png"), animations: "disabled" });
});

test("assistant home, task list and selected run logs are exclusive with real production styling", async ({ page }, info) => {
  await page.goto("/src/tests/browser/fixtures/assistant-root-cause.html");
  await expect(page.getByText("旧对话中的回答", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "任务", exact: true }).click();
  await expect(page.getByRole("log", { name: "对话消息" })).toHaveCount(0);
  await expect(page.getByPlaceholder("输入你的问题或命令")).toHaveCount(0);
  await page.getByRole("button", { name: "打开会话：生成：薄读" }).click();
  await expect(page.getByText("本次失败 · 已保存结果可用")).toBeVisible();
  await expect(page.getByRole("alert")).toContainText("离线新运行失败");
  await expect(page.getByText("薄读未完成：离线新运行失败", { exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "运行详情", exact: true }).click();
  await expect(page.getByText("薄读未完成：离线新运行失败", { exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "选择运行记录" }).click();
  await page.getByRole("option", { name: "第 1 次 · 已完成", exact: true }).click();
  await expect(page.getByText("薄读已保存，可打开阅读，也可在 Lib 的对应论文下重新打开。", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "深色", exact: true }).click();
  await page.screenshot({ path: info.outputPath("task-detail-dark.png") });
  await page.getByRole("button", { name: "新建", exact: true }).click();
  await expect(page.getByLabel("助手首页")).toBeVisible();
  await expect(page.getByRole("log", { name: "对话消息" })).toHaveCount(0);
  await expect(page.locator(".assistant-save-status")).toHaveCount(0);
  const recent = page.getByRole("list", { name: "最近对话" }).getByRole("button").first();
  await expect(recent.locator(".assistant-session-row-title")).toHaveText("离线测试问题");
  await expect(recent.locator("time")).toHaveText("刚刚");
  expect(Date.parse((await recent.locator("time").getAttribute("datetime"))!)).not.toBeNaN();
  await expect(recent).not.toContainText("条消息");
  await expect(recent).toHaveCSS("cursor", "pointer");
  await expect(recent).toHaveCSS("border-top-width", "0px");
  await expect(recent.locator(".assistant-session-row-title")).toHaveCSS("font-size", "14px");
  await expect(recent.locator(".assistant-session-row-date")).toHaveCSS("font-size", "12px");
  await page.screenshot({ path: info.outputPath("home-dark.png") });
  await page.getByRole("button", { name: "浅色", exact: true }).click();
  await expect(recent).toHaveCSS("background-color", "rgba(0, 0, 0, 0)");
  await expect(recent.locator(".assistant-session-row-date")).toBeVisible();
  await expect(page.getByRole("button", { name: "管理 离线测试问题" })).toBeVisible();
  await page.screenshot({ path: info.outputPath("home-light.png") });
  await page.getByPlaceholder("输入你的问题或命令").fill("保留新草稿");
  await expect(page.getByText("已保存到此浏览器", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByPlaceholder("输入你的问题或命令")).toHaveValue("保留新草稿");
});
